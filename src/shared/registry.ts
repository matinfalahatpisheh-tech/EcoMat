function computePublicationTimestamp(period: string, lagDays: number): string {
  const [yearStr, monthStr] = period.split('-');
  const year = Number(yearStr);
  const month = Number(monthStr);
  const date = new Date(Date.UTC(year, month, lagDays, 9, 0, 0));
  return date.toISOString();
}

